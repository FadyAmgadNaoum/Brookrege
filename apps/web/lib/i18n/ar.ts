/**
 * Arabic plural forms: 0, 1, 2, 3–10, 11+ each take a different noun form.
 * forms = [one, two, few (3–10), many (11+)]
 */
function plural(n: number, [one, two, few, many]: [string, string, string, string]) {
  if (n === 1) return one;
  if (n === 2) return two;
  const mod = n % 100;
  if (mod >= 3 && mod <= 10) return `${n} ${few}`;
  return `${n} ${many}`;
}

